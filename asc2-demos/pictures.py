print("/* Written by `pictures.py`; change the pictures there. */")
print()
print("#ifndef PICTURES_H")
print("#define PICTURES_H")
for name, art in PICTURES.items():
    rows = art.strip("\n").split("\n")
    width, height = len(rows[0]), len(rows)
    assert all(len(row) == width for row in rows), name
    print()
    print("/*")
    for row in rows:
        print("    " + row)
    print("*/")
    print(f"static unsigned int {name}[] = {{")
    print(f"    {width} | {height} << 16,")
    for row in rows:
        words = []
        for start in range(0, width, 32):
            word = 0
            for i, pixel in enumerate(row[start:start + 32]):
                if pixel == "#":
                    word |= 1 << i
            words.append(f"0x{word:08x},")
        print("    " + " ".join(words))
    print("};")
print()
print("#endif")
